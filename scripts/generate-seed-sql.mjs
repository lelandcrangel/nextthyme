// Writes db/seed/002_seed_recipes.sql from src/data/seedRecipes.ts, so the
// sample recipes have one source rather than a TypeScript copy and a SQL copy
// that drift apart.
//
//   npm run db:seed-sql         regenerate
//   npm run db:seed-sql:check   fail if the committed file is out of date
//
// The seed file is loaded through Vite's module runner rather than imported
// directly because it reads import.meta.env.BASE_URL, which only Vite defines.
// Base is '/' here and the leading slash is stripped below, so the database
// holds paths relative to the app's base and the same row works under
// /nextthyme/ in production and / in development.
//
// Re-running the generated SQL is safe: every INSERT is a no-op for an id that
// already exists, so it can never overwrite a recipe that has been edited
// since it was seeded.

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { runnerImport } from 'vite';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const outFile = path.join(root, 'db/seed/002_seed_recipes.sql');
const check = process.argv.includes('--check');

const { module } = await runnerImport(path.join(root, 'src/data/seedRecipes.ts'), {
  root,
  base: '/',
  configFile: false,
  logLevel: 'silent',
});
const recipes = module.seedRecipes;

function relativeAsset(url) {
  if (!url) return null;
  if (/^(?:[a-z]+:|\/\/)/i.test(url)) return url; // absolute: leave alone
  return url.replace(/^\/+/, '');
}

// Quoting for a literal inside single quotes. The database is utf8mb4 and the
// connection in phpMyAdmin is too, so only the quote and the backslash need
// escaping; NO_BACKSLASH_ESCAPES is not set on Hostinger.
function str(value) {
  if (value === null || value === undefined) return 'NULL';
  return `'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}
function num(value) {
  return value === null || value === undefined ? 'NULL' : String(Number(value));
}
function json(value) {
  return str(JSON.stringify(value));
}

const columns = [
  'id', 'title', 'description', 'category', 'cuisine', 'difficulty',
  'image_url', 'image_small_url', 'image_alt', 'image_credit', 'image_credit_url',
  'history', 'servings', 'yield_label',
  'prep_time_minutes', 'cook_time_minutes', 'total_time_minutes',
  'cooking_method', 'oven_temp_f',
  'tags', 'equipment', 'ingredients', 'directions', 'tips', 'nutrition', 'similar_recipe_ids',
  'next_time_notes', 'leftover_storage',
  'sort_order', 'created_at', 'updated_at',
];

const rows = recipes.map((r, index) => [
  str(r.id), str(r.title), str(r.description), str(r.category), str(r.cuisine), str(r.difficulty),
  str(relativeAsset(r.imageUrl)), str(relativeAsset(r.imageSmallUrl)),
  str(r.imageAlt ?? ''), str(r.imageCredit ?? ''), str(r.imageCreditUrl ?? ''),
  str(r.history ?? ''), num(r.servings), str(r.yieldLabel ?? ''),
  num(r.prepTimeMinutes ?? 0), num(r.cookTimeMinutes ?? 0), num(r.totalTimeMinutes ?? 0),
  str(r.cookingMethod ?? null), num(r.ovenTempF ?? null),
  json(r.tags ?? []), json(r.equipment ?? []), json(r.ingredients ?? []),
  json(r.directions ?? []), json(r.tips ?? []), json(r.nutrition ?? {}),
  json(r.similarRecipeIds ?? []),
  str(r.nextTimeNotes ?? ''), str(r.leftoverStorage ?? ''),
  num((index + 1) * 10), 'UTC_TIMESTAMP()', 'UTC_TIMESTAMP()',
]);

const sql = `-- GENERATED by scripts/generate-seed-sql.mjs from src/data/seedRecipes.ts.
-- Do not edit by hand: change the TypeScript and run \`npm run db:seed-sql\`.
--
-- Apply after 001_recipes.sql, with the Next Thyme database selected in
-- phpMyAdmin. Safe to re-run: an id that already exists is left untouched,
-- so this never overwrites a recipe that has been edited since.

-- The text below is UTF-8 (275°F, en dashes). Without this, a client whose
-- default is latin1 -- the mariadb CLI on macOS is one -- stores each
-- non-ASCII character double-encoded, and PDO later reads "275Â°F". Reading
-- back through the same client hides it, because it reverses the mistake.
SET NAMES utf8mb4;

${rows
  .map(
    (values) =>
      `INSERT INTO recipes (${columns.join(', ')})\nVALUES (${values.join(', ')})\nON DUPLICATE KEY UPDATE id = id;`,
  )
  .join('\n\n')}
`;

if (check) {
  const current = await readFile(outFile, 'utf8').catch(() => '');
  if (current !== sql) {
    console.error(`${path.relative(root, outFile)} is out of date — run npm run db:seed-sql`);
    process.exit(1);
  }
  console.log(`${path.relative(root, outFile)} is up to date (${recipes.length} recipes)`);
} else {
  await mkdir(path.dirname(outFile), { recursive: true });
  await writeFile(outFile, sql);
  console.log(`wrote ${path.relative(root, outFile)} (${recipes.length} recipes)`);
}
